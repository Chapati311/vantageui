export function PixelIcon({ id, size = 36 }: { id: string; size?: number }) {
  const rows = ICONS[id] ?? ICONS.settings;
  const pixel = size / 9;
  return (
    <svg width={size} height={size} viewBox={`0 0 ${size} ${size}`} aria-hidden="true" shapeRendering="crispEdges">
      {rows.flatMap((row, y) =>
        [...row].map((value, x) => (
          <rect key={`${x}-${y}`} x={x * pixel + 0.4} y={y * pixel + 0.4} width={pixel - 0.8} height={pixel - 0.8} className={value === '1' ? styles.pixelOn : styles.pixelOff} />
        )),
      )}
    </svg>
  );
}
